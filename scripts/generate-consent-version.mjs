#!/usr/bin/env node
/**
 * Phase 5 CR-01 fix — generate consent version at BUILD time, not runtime.
 *
 * The original `lib/consent-version.ts` read the privacy/terms .tsx files via
 * `readFileSync` at module load. Vercel's serverless bundler (nft) does NOT
 * include source `.tsx` files in the deployed function bundle by default, and
 * `process.cwd()` is computed at runtime so the trace cannot pick the paths
 * up. The first production Server Action invocation would throw ENOENT and
 * subsequent calls in the same container would also fail (sticky module-init
 * error).
 *
 * Fix: compute the SHA-256 prefix at build time and write it as a generated
 * TypeScript constant that `lib/consent-version.ts` re-exports. Build-time
 * generation removes runtime fs access entirely.
 *
 * Behavior parity with the prior runtime implementation:
 *   - SHA-256 of (privacy + terms) contents
 *   - First 8 lowercase hex chars
 *   - CRLF -> LF normalization (Pitfall 1: Windows dev / Linux build parity)
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const repoRoot = join(__dirname, '..')

function readAndNormalize(relPath) {
  const raw = readFileSync(join(repoRoot, relPath), 'utf8')
  return raw.replace(/\r\n/g, '\n')
}

const privacyContent = readAndNormalize('app/(legal)/privacy/page.tsx')
const termsContent = readAndNormalize('app/(legal)/terms/page.tsx')

const hash = createHash('sha256')
  .update(privacyContent + termsContent)
  .digest('hex')
  .slice(0, 8)

const outDir = join(repoRoot, 'lib')
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })

const outPath = join(outDir, 'consent-version.generated.ts')
const banner =
  '// AUTO-GENERATED by scripts/generate-consent-version.mjs — do not edit.\n' +
  '// Regenerated at build time from app/(legal)/privacy/page.tsx and\n' +
  '// app/(legal)/terms/page.tsx. See lib/consent-version.ts for context.\n'
const body = `export const CONSENT_VERSION = '${hash}' as const\n`
writeFileSync(outPath, banner + body)

console.log(`generate-consent-version: wrote ${outPath} (CONSENT_VERSION=${hash})`)
